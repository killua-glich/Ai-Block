#!/usr/bin/env node
// Generates a compact project map and writes it into AGENTS.md between markers.
// Agents (OpenCode, pi) auto-load AGENTS.md, so they know the codebase without scanning it.
// No dependencies: regex-based, good enough for this small React project.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs'
import { join, relative } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const SOURCE_DIRS = ['src', 'server'].map((d) => join(ROOT, d)).filter((d) => existsSync(d))
const TARGET = join(ROOT, 'AGENTS.md')
const START = '<!-- CODEMAP:START -->'
const END = '<!-- CODEMAP:END -->'

function walk(dir) {
  return readdirSync(dir).sort().flatMap((name) => {
    const p = join(dir, name)
    return statSync(p).isDirectory() ? walk(p) : [p]
  })
}

function describe(file) {
  const code = readFileSync(file, 'utf8')
  const lines = code.split('\n').length
  const info = []

  const exports = [...code.matchAll(/export\s+(?:default\s+)?(?:function|const|let|class)\s+(\w+)\s*(\([^)]*\))?/g)]
    .map((m) => m[1] + (m[2] ? m[2].replace(/\s+/g, ' ') : ''))
  const defaultId = code.match(/export\s+default\s+(\w+)\s*$/m)
  if (defaultId && !exports.some((e) => e.startsWith(defaultId[1]))) exports.push(`${defaultId[1]} (default)`)
  if (exports.length) info.push(`exports: ${exports.join(', ')}`)

  const localImports = [...code.matchAll(/from\s+['"](\.[^'"]+)['"]/g)].map((m) => m[1])
  if (localImports.length) info.push(`imports: ${localImports.join(', ')}`)

  const hooks = [...new Set([...code.matchAll(/\b(use[A-Z]\w*)\(/g)].map((m) => m[1]))]
  if (hooks.length) info.push(`hooks: ${hooks.join(', ')}`)

  const routes = [...code.matchAll(/<Route\s+path="([^"]+)"\s+element=\{<(\w+)/g)].map((m) => `${m[1]} → ${m[2]}`)
  if (routes.length) info.push(`routes: ${routes.join(', ')}`)

  const api = [...code.matchAll(/\bapp\.(get|post|put|patch|delete)\(\s*['"]([^'"]+)['"]/g)].map((m) => `${m[1].toUpperCase()} ${m[2]}`)
  if (api.length) info.push(`api: ${api.join(', ')}`)

  const tables = [...new Set([...code.matchAll(/CREATE TABLE IF NOT EXISTS\s+(\w+)/g)].map((m) => m[1]))]
  if (tables.length) info.push(`sqlite tables: ${tables.join(', ')}`)

  const storage = [...new Set([...code.matchAll(/(?:const\s+KEY\s*=\s*|localStorage\.\w+\()['"]([\w-]+)['"]/g)].map((m) => m[1]))]
  if (storage.length) info.push(`localStorage: ${storage.join(', ')}`)

  // Data files: show the shape of the first object in an array literal.
  if (file.includes('/data/')) {
    const obj = code.match(/\[\s*\{([^}]*)\}/)
    if (obj) {
      const keys = [...obj[1].matchAll(/(\w+)\s*:/g)].map((m) => m[1])
      const count = (code.match(/\{\s*id\s*:/g) || []).length
      info.push(`shape: { ${keys.join(', ')} } × ${count}`)
    }
  }

  const classes = [...new Set([...code.matchAll(/^\s*\.([\w-]+)[\s,{:]/gm)].map((m) => m[1]))]
  if (file.endsWith('.css') && classes.length) info.push(`classes: ${classes.join(', ')}`)

  return { path: relative(ROOT, file), lines, info }
}

function backlogStatus() {
  const dir = join(ROOT, 'backlog')
  if (!existsSync(dir)) return []
  return ['todo', 'in-progress', 'done'].map((s) => {
    const files = existsSync(join(dir, s)) ? readdirSync(join(dir, s)).filter((f) => f.endsWith('.md')) : []
    return `- ${s}: ${files.length ? files.map((f) => f.slice(0, 3)).join(', ') : '—'}`
  })
}

const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))
const deps = Object.entries({ ...pkg.dependencies, ...pkg.devDependencies }).map(([k, v]) => `${k}@${v}`).join(', ')

const out = [
  START,
  '<!-- Generated by `npm run codemap` (also runs on every commit). Do not edit by hand. -->',
  '',
  '### Files',
  '',
  ...SOURCE_DIRS.flatMap(walk).map(describe).map((f) => `- \`${f.path}\` (${f.lines} lines)${f.info.length ? '\n' + f.info.map((i) => `  - ${i}`).join('\n') : ''}`),
  '',
  '### Dependencies',
  '',
  deps,
  '',
  '### Backlog status',
  '',
  ...backlogStatus(),
  END,
].join('\n')

const current = readFileSync(TARGET, 'utf8')
const re = new RegExp(`${START}[\\s\\S]*?${END}`)
if (!re.test(current)) {
  console.error(`AGENTS.md is missing the ${START} / ${END} markers`)
  process.exit(1)
}
const next = current.replace(re, out)
if (next !== current) {
  writeFileSync(TARGET, next)
  console.log('codemap: AGENTS.md updated')
} else {
  console.log('codemap: up to date')
}
